import "server-only";
import { promises as fs } from "node:fs";
import path from "node:path";
import { randomUUID } from "node:crypto";

/**
 * Attachment storage backend. Local disk today; implement this interface for
 * S3 / Azure Blob and switch in getStorage().
 */
export interface StorageBackend {
  put(data: Buffer, fileName: string): Promise<string>; // returns storage key
  get(key: string): Promise<Buffer>;
  delete(key: string): Promise<void>;
}

class LocalDiskStorage implements StorageBackend {
  constructor(private root: string) {}

  private resolve(key: string) {
    // Keys are generated by us ("yyyy-mm/uuid.ext"); refuse anything that escapes the root.
    const full = path.resolve(this.root, key);
    if (!full.startsWith(path.resolve(this.root) + path.sep)) throw new Error("Invalid storage key");
    return full;
  }

  async put(data: Buffer, fileName: string) {
    const ext = path.extname(fileName).toLowerCase().replace(/[^.a-z0-9]/g, "").slice(0, 10);
    const now = new Date();
    const key = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, "0")}/${randomUUID()}${ext}`;
    const full = this.resolve(key);
    await fs.mkdir(path.dirname(full), { recursive: true });
    await fs.writeFile(full, data);
    return key;
  }

  async get(key: string) {
    return fs.readFile(this.resolve(key));
  }

  async delete(key: string) {
    await fs.rm(this.resolve(key), { force: true });
  }
}

let storage: StorageBackend | null = null;

export function getStorage(): StorageBackend {
  if (!storage) storage = new LocalDiskStorage(path.resolve(process.cwd(), process.env.UPLOAD_DIR ?? "uploads"));
  return storage;
}

export const MAX_UPLOAD_BYTES = 15 * 1024 * 1024;
